"""Generate loupmd/fasttrain/_product_poly.py: MACE's correlation-3 symmetric contraction to scalars
as explicit invariant polynomials of the 16 components x = A[n, c, :] (l <= 3).

    out[n, c] = sum_k W[s(n), k, c] P_k(x),  P = (23 cubic | 4 quadratic | 1 linear) polynomials,
    P3_k(x) = sum_{wyi} U3[w, y, i, k] x_w x_y x_i,  P2_k = sum U2[w, y, k] x_w x_y,  P1 = sum U1[w] x_w.

Four kernels over rows r = (n, c) (row and component strides are arguments, so both [rows, 16] and [16, rows] layouts work): the polynomials, their vector-Jacobian product
sum_k V_k grad P_k, their Jacobian-vector product grad P_k . T, and the Hessian-vector product
sum_k V_k (Hess P_k) T. The coupling tensors are read from a mace-torch model; the generated
module stores the symmetrised terms so a trainer can check that a model matches.

Usage: python tools/dev/gen_fasttrain_product.py MODEL
"""
import os
import sys
from collections import defaultdict
from pathlib import Path

os.environ.setdefault('TORCH_FORCE_NO_WEIGHTS_ONLY_LOAD', '1')
import torch

OUT = Path(__file__).resolve().parents[2] / 'loupmd' / 'fasttrain' / '_product_poly.py'
OUT_TERMS = OUT.with_name('_product_terms.py')     # K and TERMS alone (no Triton import: the library's checks)


sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from loupgym.fasttrain.polyterms import model_terms  # noqa: E402


def mono(m):
    return '*'.join(f'x{j}' for j in m) if m else '1.0'


def deriv(m, j):
    """d/dx_j of the monomial m: (multiplicity, remaining monomial) or None."""
    n = m.count(j)
    if n == 0:
        return None
    rest = list(m)
    rest.remove(j)
    return n, tuple(rest)


def fmt(v):
    return repr(float(v))


def emit(terms, K):
    L = []
    L.append('"""Generated by tools/dev/gen_fasttrain_product.py; do not edit."""')
    L.append('import triton')
    L.append('import triton.language as tl')
    L.append('')
    L.append('from ._product_terms import K, TERMS  # noqa: F401')
    L.append('')
    load_x = [f'    x{j} = tl.load(X + r * S16R + {j} * S16J, mask=mask, other=0.0)' for j in range(16)]
    head = ['    r = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)', '    mask = r < ROWS']

    # polynomials
    by_k = defaultdict(list)
    for k, m, v in terms:
        by_k[k].append((m, v))
    L.append('@triton.jit')
    L.append('def poly_fwd_kernel(X, P, ROWS, S16R, S16J, SKR, SKK, BLOCK: tl.constexpr):')
    L += head + load_x
    for k in range(K):
        expr = ' + '.join(f'{fmt(v)} * {mono(m)}' for m, v in by_k[k]) or '0.0 * x0'
        L.append(f'    tl.store(P + r * SKR + {k} * SKK, {expr}, mask=mask)')
    L.append('')

    # vjp: G_j = sum_k V_k dP_k/dx_j
    gj = defaultdict(list)
    for k, m, v in terms:
        for j in sorted(set(m)):
            n, rest = deriv(m, j)
            gj[j].append((k, n * v, rest))
    L.append('@triton.jit')
    L.append('def poly_vjp_kernel(X, V, G, ROWS, S16R, S16J, SKR, SKK, BLOCK: tl.constexpr):')
    L += head + load_x
    for k in range(K):
        L.append(f'    v{k} = tl.load(V + r * SKR + {k} * SKK, mask=mask, other=0.0)')
    for j in range(16):
        expr = ' + '.join(f'{fmt(c)} * v{k}' + (f' * {mono(rest)}' if rest else '') for k, c, rest in gj[j]) or '0.0 * x0'
        L.append(f'    tl.store(G + r * S16R + {j} * S16J, {expr}, mask=mask)')
    L.append('')

    # jvp: Q_k = sum_j T_j dP_k/dx_j
    L.append('@triton.jit')
    L.append('def poly_jvp_kernel(X, T, Q, ROWS, S16R, S16J, SKR, SKK, BLOCK: tl.constexpr):')
    L += head + load_x
    for j in range(16):
        L.append(f'    t{j} = tl.load(T + r * S16R + {j} * S16J, mask=mask, other=0.0)')
    qk = defaultdict(list)
    for k, m, v in terms:
        for j in sorted(set(m)):
            n, rest = deriv(m, j)
            qk[k].append((n * v, j, rest))
    for k in range(K):
        expr = ' + '.join(f'{fmt(c)} * t{j}' + (f' * {mono(rest)}' if rest else '') for c, j, rest in qk[k]) or '0.0 * x0'
        L.append(f'    tl.store(Q + r * SKR + {k} * SKK, {expr}, mask=mask)')
    L.append('')

    # hvp: H_j = sum_k V_k sum_i d2P_k/dx_j dx_i T_i
    hj = defaultdict(list)
    for k, m, v in terms:
        for j in sorted(set(m)):
            n1, rest1 = deriv(m, j)
            for i in sorted(set(rest1)):
                n2, rest2 = deriv(rest1, i)
                hj[j].append((k, n1 * n2 * v, i, rest2))
    L.append('@triton.jit')
    L.append('def poly_hvp_kernel(X, V, T, H, ROWS, S16R, S16J, SKR, SKK, BLOCK: tl.constexpr):')
    L += head + load_x
    for k in range(K):
        L.append(f'    v{k} = tl.load(V + r * SKR + {k} * SKK, mask=mask, other=0.0)')
    for j in range(16):
        L.append(f'    t{j} = tl.load(T + r * S16R + {j} * S16J, mask=mask, other=0.0)')
    for j in range(16):
        expr = ' + '.join(f'{fmt(c)} * v{k} * t{i}' + (f' * {mono(rest)}' if rest else '') for k, c, i, rest in hj[j]) or '0.0 * x0'
        L.append(f'    tl.store(H + r * S16R + {j} * S16J, {expr}, mask=mask)')
    L.append('')
    return '\n'.join(L) + '\n'


def emit_terms(terms, K):
    L = ['"""Generated by tools/dev/gen_fasttrain_product.py; do not edit."""', '', f'K = {K}', 'TERMS = [']
    for k, m, v in terms:
        L.append(f'    ({k}, {m!r}, {fmt(v)}),')
    L.append(']')
    return '\n'.join(L) + '\n'


def main():
    model = torch.load(sys.argv[1], map_location='cpu')
    all_terms = model_terms(model)
    terms, K = all_terms[0]
    assert all(t == (terms, K) for t in all_terms), 'products differ in their coupling tensors'
    OUT.write_text(emit(terms, K))
    OUT_TERMS.write_text(emit_terms(terms, K))
    print('written', OUT, 'terms', len(terms), 'K', K)


if __name__ == '__main__':
    main()
