"""Generate loupmd/fasttrain/_edge_basis.py: e3nn 0.4.4 component-normalised real spherical
harmonics through l = 3 and their Cartesian gradients, as straight-line Triton code (sympy)."""
from pathlib import Path

import sympy as sp

x, y, z = sp.symbols('ux uy uz')
s3 = sp.sqrt(3)
sh = {(0, 0): sp.Integer(1), (1, 0): x, (1, 1): y, (1, 2): z}
sh[(2, 0)] = s3 * x * z
sh[(2, 1)] = s3 * x * y
y2, x2z2 = y ** 2, x ** 2 + z ** 2
sh[(2, 2)] = y2 - sp.Rational(1, 2) * x2z2
sh[(2, 3)] = s3 * y * z
sh[(2, 4)] = s3 / 2 * (z ** 2 - x ** 2)
sh[(3, 0)] = sp.sqrt(sp.Rational(5, 6)) * (sh[(2, 0)] * z + sh[(2, 4)] * x)
sh[(3, 1)] = sp.sqrt(5) * sh[(2, 0)] * y
sh[(3, 2)] = sp.sqrt(sp.Rational(3, 8)) * (4 * y2 - x2z2) * x
sh[(3, 3)] = sp.Rational(1, 2) * y * (2 * y2 - 3 * x2z2)
sh[(3, 4)] = sp.sqrt(sp.Rational(3, 8)) * z * (4 * y2 - x2z2)
sh[(3, 5)] = sp.sqrt(5) * sh[(2, 4)] * y
sh[(3, 6)] = sp.sqrt(sp.Rational(5, 6)) * (sh[(2, 4)] * z - sh[(2, 0)] * x)


def code(e):
    import re
    t = sp.pycode(sp.N(sp.expand(e), 17))
    # Triton tensors have no __pow__: spell small integer powers as products
    return re.sub(r'(u[xyz])\*\*(\d)', lambda m: '(' + '*'.join([m.group(1)] * int(m.group(2))) + ')', t)


body = []
k = 0
for l in range(4):
    for m in range(2 * l + 1):
        P = sp.sqrt(2 * l + 1) * sh[(l, m)]
        body.append(f'    p = zero + ({code(P)})')
        body.append(f'    tl.store(Y + e * 16 + {k}, p, mask=mask)')
        for j, v in enumerate((x, y, z)):
            g = sp.diff(P, v)
            uj = ('ux', 'uy', 'uz')[j]
            # d/dv P(v/|v|) = (grad P(u) - l P(u) u) / r for homogeneous P of degree l
            body.append(f'    tl.store(JY + e * 48 + {3 * k + j}, ((zero + ({code(g)})) - {l}.0 * p * {uj}) * rinv, mask=mask)')
        k += 1

src = f'''"""Generated by tools/dev/gen_fasttrain_basis.py; do not edit."""
import triton
import triton.language as tl


@triton.jit
def edge_basis_kernel(V, Y, JY, EF, DEF, U, BW, PR, E, P: tl.constexpr, NB: tl.constexpr,
                      BLOCK: tl.constexpr):
    e = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    mask = e < E
    vx = tl.load(V + e * 3 + 0, mask=mask, other=1.0)
    vy = tl.load(V + e * 3 + 1, mask=mask, other=0.0)
    vz = tl.load(V + e * 3 + 2, mask=mask, other=0.0)
    r = tl.sqrt(vx * vx + vy * vy + vz * vz)
    rinv = 1.0 / r
    ux = vx * rinv
    uy = vy * rinv
    uz = vz * rinv
    zero = vx * 0.0
    tl.store(U + e * 3 + 0, ux, mask=mask)
    tl.store(U + e * 3 + 1, uy, mask=mask)
    tl.store(U + e * 3 + 2, uz, mask=mask)
{chr(10).join(body)}
    prefactor = tl.load(PR + 0)  # dtype scalars: Triton passes Python floats as fp32
    r_max = tl.load(PR + 1)
    t = r / r_max
    inside = tl.where(r < r_max, 1.0, 0.0)
    a = (P + 1.0) * (P + 2.0) / 2.0
    b = P * (P + 2.0)
    c = P * (P + 1.0) / 2.0
    tp1 = t
    for _ in tl.static_range(P - 2):
        tp1 = tp1 * t
    tp = tp1 * t          # t^p
    tq = tp * t           # t^(p+1)
    env = (1.0 - a * tp + b * tq - c * tq * t) * inside
    denv = (-a * P * tp1 + b * (P + 1.0) * tp - c * (P + 2.0) * tq) / r_max * inside
    for n in tl.static_range(NB):
        w = tl.load(BW + n)
        s = tl.sin(w * r)
        co = tl.cos(w * r)
        f = prefactor * s * rinv
        df = prefactor * (w * co * rinv - s * rinv * rinv)
        tl.store(EF + e * NB + n, f * env, mask=mask)
        tl.store(DEF + e * NB + n, df * env + f * denv, mask=mask)
'''
