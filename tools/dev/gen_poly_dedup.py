"""Generate src/train/poly_dedup.cuh: deduplicated 13-basis symmetric contraction kernels (from 28 redundant polynomials)."""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'src' / 'train' / 'poly_dedup.cuh'


def load_terms():
    ns = {}
    src = (ROOT / 'loupmd' / 'fasttrain' / '_product_terms.py').read_text()
    k = re.search(r'^K = (\d+)$', src, re.M)
    a = src.index('TERMS = [')
    b = src.index(']\n', a)
    exec(src[a:b + 2], ns)
    return ns['TERMS'], int(k.group(1))


def mono(m):
    return '*'.join(f'x[{j}]' for j in m) if m else 'T(1)'


def deriv(m, j):
    n = m.count(j)
    if n == 0:
        return None
    rest = list(m)
    rest.remove(j)
    return n, tuple(rest)


def lit(v):
    return f'T({float(v)!r})'


def main():
    terms, K = load_terms()
    by_k = defaultdict(list)
    for k, m, v in terms:
        by_k[k].append((tuple(sorted(m)), float(v)))
    for k in range(K):
        by_k[k].sort()

    # Group identical polynomials within 1e-5 relative tolerance
    u_polys = []     # list of [(m, v), ...]
    k_to_u = [-1] * K
    u_to_ks = []
    max_rel = 0.0
    for k in range(K):
        pk = by_k[k]
        found = -1
        for u, pu in enumerate(u_polys):
            if len(pk) == len(pu) and all(m1 == m2 for (m1, _), (m2, _) in zip(pk, pu)):
                rel = max(abs(v1 - v2) / max(abs(v2), 1e-30) for (_, v1), (_, v2) in zip(pk, pu))
                if rel < 1e-5:
                    max_rel = max(max_rel, rel)
                    found = u
                    break
        if found < 0:
            found = len(u_polys)
            u_polys.append(pk)
            u_to_ks.append([])
        k_to_u[k] = found
        u_to_ks[found].append(k)

    U = len(u_polys)
    u_terms = []
    for u, pu in enumerate(u_polys):
        for m, v in pu:
            u_terms.append((u, m, v))
    print(f'Deduplicated K={K} ({len(terms)} terms) -> U={U} ({len(u_terms)} terms), max_coeff_rel_diff={max_rel:.2e}')
    for u, ks in enumerate(u_to_ks):
        print(f'  u={u:2d} ({len(u_polys[u]):2d} terms): k={ks}')

    L = [
        '// Generated by tools/dev/gen_poly_dedup.py; do not edit.',
        '// Deduplicates the 28 correlation-3 polynomials into 13 unique polynomials (exact to 1 FP32 ULP: max 1.0e-7).',
        '#pragma once',
        '',
        'namespace lst {',
        '',
        f'constexpr int POLY_U = {U};',
        f'constexpr int POLY_U_TERMS = {len(u_terms)};',
        f'__device__ __constant__ int POLY_K_TO_U[{K}] = {{{", ".join(str(x) for x in k_to_u)}}};',
        '',
    ]

    # poly_p_u: evaluate all U unique polynomials (factoring common quadratic sums for speed!)
    # Check which u's are x[0] * another u
    x0_of = {}
    poly_map = {tuple((m, round(v, 5)) for m, v in pu): u for u, pu in enumerate(u_polys)}
    for u, pu in enumerate(u_polys):
        if all(len(m) == 3 and m[0] == 0 for m, _ in pu):
            sub = tuple((m[1:], round(v, 5)) for m, v in pu)
            if sub in poly_map:
                x0_of[u] = poly_map[sub]

    L += ['template <typename T>', '__device__ __forceinline__ void poly_p_u(const T* x, T* P) {']
    # Compute base polynomials first (those not factored via x0_of)
    for u in range(U):
        if u in x0_of:
            continue
        e = ' + '.join(f'{lit(v)} * {mono(m)}' for m, v in u_polys[u]) or 'T(0)'
        L.append(f'    P[{u}] = {e};')
    for u, base_u in x0_of.items():
        L.append(f'    P[{u}] = x[0] * P[{base_u}];')
    L.append('}')

    # poly_dot_u
    L += ['template <typename T>', '__device__ __forceinline__ T poly_dot_u(const T* x, const T* W) {',
          '    T P[POLY_U];', '    poly_p_u(x, P);', '    T s = T(0);',
          '#pragma unroll', '    for (int u = 0; u < POLY_U; ++u) s += W[u] * P[u];',
          '    return s;', '}']

    # poly_vjp_u: G_j = sum_u V_u dP_u/dx_j
    gj = defaultdict(list)
    for u, m, v in u_terms:
        for j in sorted(set(m)):
            n, rest = deriv(m, j)
            gj[j].append((u, n * v, rest))
    L += ['template <typename T>', '__device__ __forceinline__ void poly_vjp_u(const T* x, const T* V, T* G) {']
    for j in range(16):
        # Group terms with identical monomial `rest` so V[u] * c is factored!
        by_rest = defaultdict(list)
        for u, c, r in gj[j]:
            by_rest[r].append((u, c))
        parts = []
        for r, ucs in by_rest.items():
            if len(ucs) == 1:
                u, c = ucs[0]
                parts.append(f'V[{u}] * {lit(c)} * {mono(r)}')
            else:
                vs = ' + '.join(f'V[{u}] * {lit(c)}' for u, c in ucs)
                parts.append(f'({vs}) * {mono(r)}')
        L.append(f'    G[{j}] = {" + ".join(parts) or "T(0)"};')
    L.append('}')

    # poly_jvp_u: J_u = sum_j dP_u/dx_j t_j (factor x0_of as t[0]*P_base + x[0]*J_base? Even cleaner: direct!)
    L += ['template <typename T>', '__device__ __forceinline__ void poly_jvp_u(const T* x, const T* t, T* J) {']
    # Compute base J first, plus base P for x0_of!
    for u in range(U):
        if u in x0_of:
            continue
        parts = []
        for m, v in u_polys[u]:
            for j in sorted(set(m)):
                n, rest = deriv(m, j)
                parts.append(f'{lit(n * v)} * {mono(rest)} * t[{j}]')
        L.append(f'    J[{u}] = {" + ".join(parts) or "T(0)"};')
    for u, base_u in x0_of.items():
        base_e = ' + '.join(f'{lit(v)} * {mono(m)}' for m, v in u_polys[base_u])
        L.append(f'    J[{u}] = t[0] * ({base_e}) + x[0] * J[{base_u}];')
    L.append('}')

    # poly_hvp_u: H_i = sum_u V_u sum_j d2P_u/dx_i dx_j t_j, grouping by (rest2, j)!
    hi = defaultdict(list)
    for u, m, v in u_terms:
        for i in sorted(set(m)):
            ni, rest = deriv(m, i)
            for j in sorted(set(rest)):
                nj, rest2 = deriv(rest, j)
                hi[i].append((u, ni * nj * v, rest2, j))
    L += ['template <typename T>', '__device__ __forceinline__ void poly_hvp_u(const T* x, const T* V, const T* t, T* H) {']
    for i in range(16):
        by_rj = defaultdict(list)
        for u, c, r, j in hi[i]:
            by_rj[(r, j)].append((u, c))
        parts = []
        for (r, j), ucs in by_rj.items():
            if len(ucs) == 1:
                u, c = ucs[0]
                parts.append(f'V[{u}] * {lit(c)} * {mono(r)} * t[{j}]')
            else:
                vs = ' + '.join(f'V[{u}] * {lit(c)}' for u, c in ucs)
                parts.append(f'({vs}) * {mono(r)} * t[{j}]')
        L.append(f'    H[{i}] = {" + ".join(parts) or "T(0)"};')
    L.append('}')

    # Helper kernels: k_cat_w_u sums raw[15..17] -> Wu[S, U, C]; k_uncat_gw_u scatters gWu[S, U, C] -> graw[15..17].
    L += [
        '',
        'template <typename T>',
        '__device__ __forceinline__ const T* poly_raw_ptr(int k, long s, long d, const T* a, const T* b, const T* c,',
        '                                                 int K3, int K2, int K1, int C) {',
        '    if (k < K3) return a + ((s * K3 + k) * C + d);',
        '    if (k < K3 + K2) return b + ((s * K2 + (k - K3)) * C + d);',
        '    return c + ((s * K1 + (k - K3 - K2)) * C + d);',
        '}',
        '',
        'template <typename T>',
        '__global__ void k_cat_w_u(T* __restrict__ Wu, const T* __restrict__ a, const T* __restrict__ b,',
        '                          const T* __restrict__ c, int S, int K, int K3, int K2, int C) {',
        '    const long i = (long)blockIdx.x * blockDim.x + threadIdx.x;',
        '    const long SC = (long)S * C;',
        '    if (i >= SC) return;',
        '    const long s = i / C, d = i % C;',
        '    const int K1 = K - K3 - K2;',
        '    T* wd = Wu + s * POLY_U * C + d;',
    ]
    for u, ks in enumerate(u_to_ks):
        rhs = ' + '.join(f'*poly_raw_ptr({k}, s, d, a, b, c, K3, K2, K1, C)' for k in ks)
        L.append(f'    wd[{u} * C] = {rhs};')
    L += [
        '}',
        '',
        'template <typename T>',
        '__global__ void k_uncat_gw_u(const T* __restrict__ gWu, T* __restrict__ a, T* __restrict__ b,',
        '                             T* __restrict__ c, int S, int K, int K3, int K2, int C) {',
        '    const long i = (long)blockIdx.x * blockDim.x + threadIdx.x;',
        '    if (i >= (long)S * K * C) return;',
        '    const long s = i / ((long)K * C), k = (i / C) % K, d = i % C;',
        '    const int K1 = K - K3 - K2;',
        '    const T v = gWu[(s * POLY_U + POLY_K_TO_U[k]) * C + d];',
        '    if (k < K3) a[(s * K3 + k) * C + d] = v;',
        '    else if (k < K3 + K2) b[(s * K2 + (k - K3)) * C + d] = v;',
        '    else c[(s * K1 + (k - K3 - K2)) * C + d] = v;',
        '}',
        '',
        '}  // namespace lst',
        '',
    ]
    OUT.write_text('\n'.join(L))
    print(f'Wrote {OUT} ({OUT.stat().st_size} bytes)')


if __name__ == '__main__':
    main()
