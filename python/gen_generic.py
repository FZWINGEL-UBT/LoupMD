                ch_body.append(f"        if (WANT_DX) {{ dx1_0 = fmaf(w, {qs[0]}, dx1_0); dx1_1 = fmaf(w, {qs[1]}, dx1_1); dx1_2 = fmaf(w, {qs[2]}, dx1_2); }}")
