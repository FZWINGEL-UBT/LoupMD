def lit(v):
    return float(np.float32(v)).hex() + "f"


# ----------------------------------------------------------------------------------------------- SH gradient
def sh16_grad_source():
    x, y, z = sp.symbols("x y z", real=True)
    s3, s5, s56, s38 = sp.sqrt(3), sp.sqrt(5), sp.sqrt(sp.Rational(5, 6)), sp.sqrt(sp.Rational(3, 8))
    c1, c2, c3 = sp.sqrt(3), sp.sqrt(5), sp.sqrt(7)
    s20, s21 = s3 * x * z, s3 * x * y
    y2, x2z2 = y * y, x * x + z * z
    s22 = y2 - x2z2 / 2
    s23 = s3 * y * z
    s24 = s3 / 2 * (z * z - x * x)
    s30 = s56 * (s20 * z + s24 * x)
    s31 = s5 * s20 * y
    s32 = s38 * (4 * y2 - x2z2) * x
    s33 = y * (2 * y2 - 3 * x2z2) / 2
    s34 = s38 * z * (4 * y2 - x2z2)
    s35 = s5 * s24 * y
    s36 = s56 * (s24 * z - s20 * x)
    Y = [sp.Integer(1), c1 * x, c1 * y, c1 * z] + [c2 * e for e in (s20, s21, s22, s23, s24)] + \
        [c3 * e for e in (s30, s31, s32, s33, s34, s35, s36)]
    d = sp.symbols("d0:16", real=True)
    g = [sp.expand(sum(d[m] * sp.diff(Y[m], v) for m in range(16))) for v in (x, y, z)]
    reps, red = sp.cse(g, symbols=sp.numbered_symbols("t"))
    lines = ["// Gradient of edge_sh16's 16 values, contracted with d[16], with respect to the unit vector (x, y, z)",
             "// (components treated as independent; the caller projects out the radial part). Generated by sympy.",
             "__device__ __forceinline__ void sh16_grad(float x, float y, float z, const float* d, float& gx, float& gy,"
             " float& gz) {"]
    for i in range(16):
        lines.append(f"  const float d{i} = d[{i}];")
    for s, e in reps:
        lines.append(f"  const float {s} = {sp.ccode(sp.N(e, 17)).replace('pow', 'powf')};")
    for name, e in zip(("gx", "gy", "gz"), red):
        lines.append(f"  {name} = {sp.ccode(sp.N(e, 17))};")
    lines.append("}")
    src = "\n".join(lines) + "\n"
    # float literals
    import re
    src = re.sub(r"(?<![\w.])(\d+\.\d+(?:e[-+]?\d+)?)(?![\w.])", lambda m: lit(float(m.group(1))), src)
    return src


# ----------------------------------------------------------------------------------------------- conv kernels
def w3j(l1, l2, l3):
    return o3.wigner_3j(l1, l2, l3, dtype=torch.float64).numpy()


def conv_layout(lx):
    paths = eg.conv_paths(lx)
    slot = {}  # path k -> (l3, j: index within the paths of degree l3)
    count = {l: 0 for l in range(4)}
    for k, (_, _, l3) in enumerate(paths):
        slot[k] = (l3, count[l3])
        count[l3] += 1
    return paths, slot, count


def _ptr_args(prefix, ls, const=True):
    q = "const float* __restrict__" if const else "float* __restrict__"
    return ", ".join(f"{q} {prefix}{l}" for l in ls)


def emit_conv_fwd(lx):
    paths, slot, count = conv_layout(lx)
    L = []
    L.append(f'extern "C" __global__ void __launch_bounds__(512) gconv_fwd_L{lx}(')
    L.append("    int N, int C, int S, int I, int Q1, SplineGrid grid, int sh_perm, int pair_sym,")
    L.append("    const int* __restrict__ row_ptr, const int* __restrict__ senders, const float4* __restrict__ vec_len,")
    L.append("    const int* __restrict__ species, const float4* __restrict__ table,")
    L.append(f"    {_ptr_args('x', range(lx + 1))},")
    L.append(f"    {_ptr_args('mid', range(4), const=False)}, float* __restrict__ D) {{")
    L.append("  const int a = blockIdx.x, c = threadIdx.x;")
    L.append("  if (a >= N) return;")
    L.append("  const int sa = species[a];")
    nacc = sum(2 * l3 + 1 for _, _, l3 in paths)
    L.append(f"  float acc[{nacc}];")
    L.append(f"  #pragma unroll\n  for (int i = 0; i < {nacc}; ++i) acc[i] = 0.0f;")
    L.append("  float dsum = 0.0f;")
    L.append("  const int e_end = row_ptr[a + 1];")
    L.append("  for (int e = row_ptr[a]; e < e_end; ++e) {")
    L.append("    const float4 vl = vec_len[e];")
    L.append("    const int s = senders[e];")
    L.append("    float4 Yv[4];")
    L.append("    if (sh_perm) loup::edge_sh16(vl.y, vl.z, vl.x, vl.w, Yv); else loup::edge_sh16(vl.x, vl.y, vl.z, vl.w, Yv);")
    L.append("    const float Y[16] = {Yv[0].x, Yv[0].y, Yv[0].z, Yv[0].w, Yv[1].x, Yv[1].y, Yv[1].z, Yv[1].w,")
    L.append("                         Yv[2].x, Yv[2].y, Yv[2].z, Yv[2].w, Yv[3].x, Yv[3].y, Yv[3].z, Yv[3].w};")
    L.append("    int iv; float t, sxi;")
    L.append("    locate_spline(grid, vl.w, iv, t, sxi);")
    L.append("    const int pr = pair_sym ? loup::sym_pair(species[s], sa, S) : species[s] * S + sa;")
    L.append("    const float4* tp = table + ((int64_t)pr * I + iv) * Q1;")
    for l in range(lx + 1):
        for m in range(2 * l + 1):
            L.append(f"    const float x{l}_{m} = __ldg(x{l} + ((int64_t)s * {2 * l + 1} + {m}) * C + c);")
    off = 0
    for k, (l1, l2, l3) in enumerate(paths):
        W = w3j(l1, l2, l3)
        L.append(f"    {{ const float4 cf = __ldg(tp + {k} * C + c);")
        L.append("      const float R = fmaf(t, fmaf(t, fmaf(t, cf.w, cf.z), cf.y), cf.x);")
        for m3 in range(2 * l3 + 1):
            terms = []
            for m1 in range(2 * l1 + 1):
                for m2 in range(2 * l2 + 1):
                    v = W[m1, m2, m3]
                    if abs(v) > 1e-12:
                        terms.append(f"{lit(v)} * x{l1}_{m1} * Y[{l2 * l2 + m2}]")
            if terms:
                L.append(f"      acc[{off + m3}] = fmaf(R, {' + '.join(terms)}, acc[{off + m3}]);")
        L.append("    }")
        off += 2 * l3 + 1
    L.append("    if (c == 0) {")
    L.append("      const float4 cf = __ldg(tp + Q1 - 1);")
    L.append("      dsum += fmaf(t, fmaf(t, fmaf(t, cf.w, cf.z), cf.y), cf.x);")
    L.append("    }")
    L.append("  }")
    off = 0
    for k, (l1, l2, l3) in enumerate(paths):
        _, j = slot[k]
        n = count[l3]
        for m3 in range(2 * l3 + 1):
            L.append(f"  mid{l3}[((int64_t)a * {2 * l3 + 1} + {m3}) * {n} * C + {j} * C + c] = acc[{off + m3}];")
        off += 2 * l3 + 1
    L.append("  if (c == 0) D[a] = dsum;")
    L.append("}")
    return "\n".join(L) + "\n"


def emit_conv_bwd(lx):
    paths, slot, count = conv_layout(lx)
    L = []
    L.append(f'extern "C" __global__ void __launch_bounds__(512) gconv_bwd_L{lx}(')
    L.append("    int N, int C, int S, int I, int Q1, SplineGrid grid, int sh_perm, int pair_sym,")
    L.append("    const int* __restrict__ row_ptr, const int* __restrict__ senders, const float4* __restrict__ vec_len,")
    L.append("    const int* __restrict__ species, const float4* __restrict__ table,")
    L.append(f"    {_ptr_args('x', range(lx + 1))},")
    L.append(f"    {_ptr_args('dmid', range(4))}, const float* __restrict__ dD,")
    L.append(f"    {_ptr_args('dx', range(lx + 1), const=False)}, int want_dx, float* __restrict__ edge_dvec) {{")
    L.append("  const int a = blockIdx.x, c = threadIdx.x, lane = c & 31;")
    L.append("  if (a >= N) return;")
    L.append("  const int sa = species[a];")
    # gradient of mid per path, kept in registers
    G = {}
    for k, (l1, l2, l3) in enumerate(paths):
        _, j = slot[k]
        n = count[l3]
        for m3 in range(2 * l3 + 1):
            G[k, m3] = f"G{k}_{m3}"
            L.append(f"  const float G{k}_{m3} = __ldg(dmid{l3} + ((int64_t)a * {2 * l3 + 1} + {m3}) * {n} * C + {j} * C + c);")
    L.append("  const float dDa = dD ? dD[a] : 0.0f;")
    L.append("  const int e_end = row_ptr[a + 1];")
    L.append("  for (int e = row_ptr[a]; e < e_end; ++e) {")
    L.append("    const float4 vl = vec_len[e];")
    L.append("    const int s = senders[e];")
    L.append("    float4 Yv[4];")
    L.append("    const float ux = sh_perm ? vl.y : vl.x, uy = sh_perm ? vl.z : vl.y, uz = sh_perm ? vl.x : vl.z;")
    L.append("    loup::edge_sh16(ux, uy, uz, vl.w, Yv);")
    L.append("    const float Y[16] = {Yv[0].x, Yv[0].y, Yv[0].z, Yv[0].w, Yv[1].x, Yv[1].y, Yv[1].z, Yv[1].w,")
    L.append("                         Yv[2].x, Yv[2].y, Yv[2].z, Yv[2].w, Yv[3].x, Yv[3].y, Yv[3].z, Yv[3].w};")
    L.append("    int iv; float t, sxi;")
    L.append("    locate_spline(grid, vl.w, iv, t, sxi);")
    L.append("    const int pr = pair_sym ? loup::sym_pair(species[s], sa, S) : species[s] * S + sa;")
    L.append("    const float4* tp = table + ((int64_t)pr * I + iv) * Q1;")
    for l in range(lx + 1):
        for m in range(2 * l + 1):
            L.append(f"    const float x{l}_{m} = __ldg(x{l} + ((int64_t)s * {2 * l + 1} + {m}) * C + c);")
            L.append(f"    float gx{l}_{m} = 0.0f;")
    L.append("    float dY[16];")
    L.append("    #pragma unroll\n    for (int i = 0; i < 16; ++i) dY[i] = 0.0f;")
    L.append("    float er = 0.0f;")
    for k, (l1, l2, l3) in enumerate(paths):
        W = w3j(l1, l2, l3)
        L.append(f"    {{ const float4 cf = __ldg(tp + {k} * C + c);")
        L.append("      const float R = fmaf(t, fmaf(t, fmaf(t, cf.w, cf.z), cf.y), cf.x);")
        L.append("      const float dR = fmaf(t, fmaf(t, 3.0f * cf.w, 2.0f * cf.z), cf.y) * sxi;")
        # A[m1][m2] = sum_m3 W G[m3]
        A = {}
        for m1 in range(2 * l1 + 1):
            for m2 in range(2 * l2 + 1):
                terms = [f"{lit(W[m1, m2, m3])} * {G[k, m3]}" for m3 in range(2 * l3 + 1) if abs(W[m1, m2, m3]) > 1e-12]
                if terms:
                    nm = f"A{m1}_{m2}"
                    L.append(f"      const float {nm} = {' + '.join(terms)};")
                    A[m1, m2] = nm
        # tR = sum A x Y
        tr = [f"{A[m1, m2]} * x{l1}_{m1} * Y[{l2 * l2 + m2}]" for (m1, m2) in A]
        L.append(f"      const float tR = {' + '.join(tr) if tr else '0.0f'};")
        L.append("      er = fmaf(tR, dR, er);")
        for m2 in range(2 * l2 + 1):
            terms = [f"{A[m1, m2]} * x{l1}_{m1}" for m1 in range(2 * l1 + 1) if (m1, m2) in A]
            if terms:
                L.append(f"      dY[{l2 * l2 + m2}] = fmaf(R, {' + '.join(terms)}, dY[{l2 * l2 + m2}]);")
        for m1 in range(2 * l1 + 1):
            terms = [f"{A[m1, m2]} * Y[{l2 * l2 + m2}]" for m2 in range(2 * l2 + 1) if (m1, m2) in A]
            if terms:
                L.append(f"      gx{l1}_{m1} = fmaf(R, {' + '.join(terms)}, gx{l1}_{m1});")
        L.append("    }")
    L.append("    if (c == 0 && dDa != 0.0f) {")
    L.append("      const float4 cf = __ldg(tp + Q1 - 1);")
    L.append("      er = fmaf(dDa, fmaf(t, fmaf(t, 3.0f * cf.w, 2.0f * cf.z), cf.y) * sxi, er);")
    L.append("    }")
    L.append("    if (want_dx) {")
    for l in range(lx + 1):
        for m in range(2 * l + 1):
            L.append(f"      atomicAdd(dx{l} + ((int64_t)s * {2 * l + 1} + {m}) * C + c, gx{l}_{m});")
    L.append("    }")
    L.append("    // This thread's share of dE/dvec (radial part + SH part through the unit vector), reduced over the warp")
    L.append("    // and added once per warp: no block-wide barrier per edge.")
    L.append("    const float dd = vl.w > loup::EPS_SH ? vl.w : loup::EPS_SH;")
    L.append("    const float inv_d = 1.0f / dd;")
    L.append("    const float x = ux * inv_d, y = uy * inv_d, z = uz * inv_d;")
    L.append("    dY[0] = 0.0f;")
    L.append("    float gx, gy, gz;")
    L.append("    sh16_grad(x, y, z, dY, gx, gy, gz);")
    L.append("    const float dot = x * gx + y * gy + z * gz;")
    L.append("    float fx = x * er + (gx - x * dot) * inv_d;")
    L.append("    float fy = y * er + (gy - y * dot) * inv_d;")
    L.append("    float fz = z * er + (gz - z * dot) * inv_d;")
    L.append("    #pragma unroll")
    L.append("    for (int off = 16; off > 0; off >>= 1) {")
    L.append("      fx += __shfl_xor_sync(0xffffffffu, fx, off);")
    L.append("      fy += __shfl_xor_sync(0xffffffffu, fy, off);")
    L.append("      fz += __shfl_xor_sync(0xffffffffu, fz, off);")
    L.append("    }")
    L.append("    if (lane == 0) {")
    L.append("      if (sh_perm) { const float tx = fx, ty = fy, tz = fz; fx = tz; fy = tx; fz = ty; }")
    L.append("      atomicAdd(edge_dvec + (int64_t)e * 3 + 0, fx);")
    L.append("      atomicAdd(edge_dvec + (int64_t)e * 3 + 1, fy);")
    L.append("      atomicAdd(edge_dvec + (int64_t)e * 3 + 2, fz);")
    L.append("    }")
    L.append("  }")
    L.append("}")
    return "\n".join(L) + "\n"


# ----------------------------------------------------------------------------------------------- products
def _ssa(lines, i, op):
    from fastmace.kernels.cuda.sc_factored import _emit_node

    _emit_node(lines, i, op)


def emit_product(sig, prog, feats, sh):
    from fastmace.kernels.cuda.sc_factored import _expr, _literal

    seg_in, seg_w, seg_out, _ = sh
    assert seg_in == 16, seg_in
    lo = int(round(seg_out ** 0.5)) - 1
    assert (lo + 1) ** 2 == seg_out
    roots = [u for f in feats for u in (f or {}).values() if u is not None]
    used = prog.used(roots)
    head = [
        "  const int a = blockIdx.x, c = blockIdx.y * 32 + threadIdx.x;",
        "  const float s = D ? 1.0f / (D[a] + 1.0f) : 1.0f;",
        "  const float* wr = w + (int64_t)sp[a] * w_stride + c;",
    ]
    loads = []
    for l in range(4):
        for m in range(2 * l + 1):
            loads.append(f"  const float x{l * l + m} = __ldg(m{l} + ((int64_t)a * {2 * l + 1} + {m}) * C + c) * s;")
    args_in = "int N, int C, " + _ptr_args("m", range(4)) + \
        ", const float* __restrict__ D, const float* __restrict__ w, int64_t w_stride, const int* __restrict__ sp"
    F = [f'extern "C" __global__ void __launch_bounds__(32) gprod_fwd_{sig}(',
         f"    {args_in}, {_ptr_args('y', range(lo + 1), const=False)}) {{"] + head + loads
    for i in used:
        _ssa(F, i, prog.nodes[i])
    F.append("  float " + ", ".join(f"o{cc} = 0.0f" for cc in range(seg_out)) + ";")
    for b, f in enumerate(feats):
        items = [(cc, u) for cc, u in sorted((f or {}).items()) if u is not None]
        if items:
            F.append(f"  {{ const float wb = __ldg(wr + {b} * C);")
            F += [f"    o{cc} = fmaf(wb, {_expr(u)}, o{cc});" for cc, u in items]
            F.append("  }")
    for l in range(lo + 1):
        for m in range(2 * l + 1):
            F.append(f"  y{l}[((int64_t)a * {2 * l + 1} + {m}) * C + c] = o{l * l + m};")
    F.append("}")

    B = [f'extern "C" __global__ void __launch_bounds__(32) gprod_bwd_{sig}(',
         f"    {args_in}, {_ptr_args('gin', range(lo + 1))},",
         f"    {_ptr_args('dm', range(4), const=False)}, float* __restrict__ dD) {{"] + head + loads
    for l in range(lo + 1):
        for m in range(2 * l + 1):
            B.append(f"  const float g{l * l + m} = __ldg(gin{l} + ((int64_t)a * {2 * l + 1} + {m}) * C + c);")
    for i in used:
        _ssa(B, i, prog.nodes[i])
    adj = {}

    def add(u, ab):
        name = f"d{_expr(u)}"
        a_, b_ = ab
        if u in adj:
            B.append(f"  {name} = fmaf({a_}, {b_}, {name});")
        else:
            B.append(f"  float {name} = {a_} * {b_};")
        adj[u] = name

    for b, f in enumerate(feats):
        items = [(cc, u) for cc, u in sorted((f or {}).items()) if u is not None]
        if not items:
            continue
        B.append(f"  const float w{b} = __ldg(wr + {b} * C);")
        for cc, u in items:
            add(u, (f"w{b}", f"g{cc}"))
    for i in reversed(used):
        if i not in adj:
            continue
        op, da = prog.nodes[i], adj[i]
        if op[0] == "mul":
            add(op[1], (da, _expr(op[2])))
            add(op[2], (da, _expr(op[1])))
        elif op[0] == "lin":
            for cc, u in op[1]:
                add(u, (_literal(cc), da))
        else:
            for a_, b_ in op[1]:
                add(a_, (da, _expr(b_)))
                add(b_, (da, _expr(a_)))
    B.append("  float dot = 0.0f;")
    for l in range(4):
        for m in range(2 * l + 1):
            i = l * l + m
            dx = adj.get(-1 - i, "0.0f")
            B.append(f"  dot = fmaf({dx}, x{i}, dot);")
            B.append(f"  dm{l}[((int64_t)a * {2 * l + 1} + {m}) * C + c] = {dx} * s;")
    B += ["  if (dD) {",
          "    #pragma unroll",
          "    for (int off = 16; off > 0; off >>= 1) dot += __shfl_xor_sync(0xffffffffu, dot, off);",
          "    if (threadIdx.x == 0) atomicAdd(dD + a, -s * dot);",
          "  }",
          "}"]
    return "\n".join(F) + "\n\n" + "\n".join(B) + "\n", lo


def main():
    models_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "/home/fzwin/models")
    out = Path(sys.argv[2] if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "src" / "generated_generic.cuh")
    from fastmace.kernels.cuda.sc_factored import factor
    from fastmace.kernels.cuda.sc_generated import merged_terms, shape_of
    from mace.cli.convert_e3nn_cueq import run as convert_e3nn_cueq

    parts = ["#pragma once", "// Auto-generated by LoupMD/python/gen_generic.py. Do not edit.",
             '#include "kernels_common.cuh"', "#include <cuda_runtime.h>", "#include <cstdint>", "",
             sh16_grad_source()]
    for lx in LX:
        parts.append(emit_conv_fwd(lx))
        parts.append(emit_conv_bwd(lx))
    table = []
    seen = set()
    for fname, idx in PRODUCT_SOURCES:
        m = torch.load(models_dir / fname, map_location="cpu", weights_only=False).float()
        mc = convert_e3nn_cueq(m)
        sc = mc.products[idx].symmetric_contractions
        sh = shape_of(sc)
        prog, feats, _ = factor(merged_terms(sc.etp.polynomial), sh[0], sh[1], sh[2])
        sig = eg.product_signature(prog, feats, sh)
        if sig in seen:
            continue
        seen.add(sig)
        src, lo = emit_product(sig, prog, feats, sh)
        parts.append(src)
        table.append((sig, lo, sh[1]))
        print(f"product {fname}[{idx}]: sig {sig}, lmax_out {lo}, segments_w {sh[1]}")
    # dispatch table
    parts.append("struct GProdKernels { const char* sig; int lmax_out; int segments_w; const void* fwd; const void* bwd; };")
    parts.append("static const GProdKernels kGProd[] = {")
    for sig, lo, segw in table:
        parts.append(f'    {{"{sig}", {lo}, {segw}, (const void*)gprod_fwd_{sig}, (const void*)gprod_bwd_{sig}}},')
    parts.append("};")
    out.write_text("\n".join(parts) + "\n")
