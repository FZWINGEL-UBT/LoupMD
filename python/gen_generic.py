"""Generate LoupMD/src/generated_generic.cuh: the generic engine's model-shape kernels.

  python gen_generic.py MODELS_DIR [OUT]

  * gconv_fwd_L{lx} / gconv_bwd_L{lx}, lx = 0, 1, 2: the conv tensor product (input degrees 0..lx, SH l <= 3,
    target 0e+1o+2e+3o, paths as export_generic.conv_paths) fused with the radial spline lookup and the receiver
    sum (forward), and its reverse mode (sender-feature gradients by atomics, per-edge dE/dvec accumulated).
    One block per receiver, one thread per channel (blockDim = C, a multiple of 32, at most 512).
  * gprod_fwd_<sig> / gprod_bwd_<sig>: the factored symmetric contraction (FastMACE sc_factored) of each product
    configuration found in the models, keyed by export_generic.product_signature. Grid (N, C / 32), one warp each.
  * sh16_grad: the gradient of edge_sh16 (kernels_common.cuh) with respect to the unit vector, from sympy.
"""
