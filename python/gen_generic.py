def emit_conv_bwd_L2(groups=(0, 1, 2)):
    lx = 2
    paths, slot, count = layout(lx)
    n_paths = len(paths)
    by_l1 = {0: [], 1: [], 2: []}
    for k, (l1, l2, l3) in enumerate(paths):
        by_l1[l1].append((k, l1, l2, l3))
    # The receiver's dmid values of the emitted paths, staged once per block (they depend on (receiver, channel)
    # only): s_g[ch * GS + gofs[k] + m3], GS odd so the channel-strided reads are bank-conflict free.
    gofs, GS = {}, 0
    for l1 in groups:
        for k, _, _, l3 in by_l1[l1]:
            gofs[k] = GS
            GS += 2 * l3 + 1
    if GS % 2 == 0:
        GS += 1
    pro = ["  for (int ch = tid; ch < C; ch += blockDim.x) {"]
    for l1 in groups:
        for k, _, _, l3 in by_l1[l1]:
            _, j = slot[k]
            for m3 in range(2 * l3 + 1):
                pro.append(f"    s_g[ch * {GS} + {gofs[k] + m3}] = __ldg(dmid{l3} + ((int64_t)rcv * {2 * l3 + 1} + {m3}) * {count[l3]} * C + {j} * C + ch);")
    pro.append("  }")
    pro.append("  __syncthreads();")

    ch_body = []
    for l1 in groups:
        ch_body.append(f"      {{ // a = {l1} group")
        for m in range(2 * l1 + 1):
            ch_body.append(f"        const float x{l1}_{m} = __ldg(x{l1}_p + ((int64_t)snd * {2 * l1 + 1} + {m}) * C + ch);")
            ch_body.append(f"        float gx{l1}_{m} = 0.0f;")
        for k, _, l2, l3 in by_l1[l1]:
            W = o3.wigner_3j(l1, l2, l3, dtype=torch.float64).numpy()
            _, j = slot[k]
            n = count[l3]
            ch_body.append(f"        {{ // path {k} ({l1},{l2},{l3})")
            ch_body.append(f"          const uint2 c = __ldg(tq + {k} * C + ch);")
            ch_body.append("          const unsigned eb0 = (c.y & 0x0F800000u) + bias_shift;")
            ch_body.append("          const float eb_f = __uint_as_float(eb0);")
            ch_body.append("          const float r0 = __uint_as_float((c.x & 0x7FFFF8u) | eb0);")
            ch_body.append("          const float r1 = __uint_as_float((c.y & 0x7FFFF0u) | eb0);")
            ch_body.append("          const float r2 = __uint_as_float((__funnelshift_l(c.x, c.x, 20) & 0x7FF800u) | eb0);")
            ch_body.append("          const float r3 = __uint_as_float((__funnelshift_l(c.y, c.y, 19) & 0x7F8000u) | eb0);")
            ch_body.append("          const float R = fmaf(s3, r3, fmaf(s2, r2, fmaf(s1, r1, fmaf(nw_hb, eb_f, r0))));")
            ch_body.append("          const float dw = fmaf(ds3, r3, fmaf(ds2, r2, fmaf(ndt_hb, eb_f, r1)));")
            for m3 in range(2 * l3 + 1):
                ch_body.append(f"          const float g{m3} = s_g[ch * {GS} + {gofs[k] + m3}];")
            A = {}
            for m1 in range(2 * l1 + 1):
                for m2 in range(2 * l2 + 1):
                    terms = [f"{lit(W[m1, m2, m3])} * g{m3}" for m3 in range(2 * l3 + 1) if abs(W[m1, m2, m3]) > 1e-12]
                    if terms:
                        ch_body.append(f"          const float A{m1}_{m2} = {' + '.join(terms)};")
                        A[m1, m2] = f"A{m1}_{m2}"
            # Old form (other GPUs): pull_R from the full sum over A x Y, then the dY and x-gradient contractions.
            old = []
            tr = [f"{A[m1, m2]} * x{l1}_{m1} * Y{l2 * l2 + m2}" for (m1, m2) in A]
            old.append(f"          pull_R = fmaf({' + '.join(tr) if tr else '0.0f'}, dw, pull_R);")
            for m2 in range(2 * l2 + 1):
                terms = [f"{A[m1, m2]} * x{l1}_{m1}" for m1 in range(2 * l1 + 1) if (m1, m2) in A]
                if terms:
                    old.append(f"          dY[{l2 * l2 + m2}] = fmaf(R, {' + '.join(terms)}, dY[{l2 * l2 + m2}]);")
            for m1 in range(2 * l1 + 1):
                terms = [f"{A[m1, m2]} * Y{l2 * l2 + m2}" for m2 in range(2 * l2 + 1) if (m1, m2) in A]
                if terms:
                    old.append(f"          gx{l1}_{m1} = fmaf(R, {' + '.join(terms)}, gx{l1}_{m1});")
            # sm_120 (S48): the x gradient's Cg[m1] = sum_m2 A[m1, m2] Y[m2] also gives the radial pull,
            # sum_m1 x[m1] Cg[m1] = sum_{m1, m2} A x Y: one term per m1 instead of one per A entry (-10% SASS).
            new, cg_names = [], []
            for m1 in range(2 * l1 + 1):
                terms = [f"{A[m1, m2]} * Y{l2 * l2 + m2}" for m2 in range(2 * l2 + 1) if (m1, m2) in A]
                if terms:
                    new.append(f"          const float Cg{m1} = {' + '.join(terms)};")
                    cg_names.append((m1, f"Cg{m1}"))
            tr = [f"x{l1}_{m1} * {cgn}" for m1, cgn in cg_names]
            new.append(f"          pull_R = fmaf({' + '.join(tr) if tr else '0.0f'}, dw, pull_R);")
            for m2 in range(2 * l2 + 1):
                terms = [f"{A[m1, m2]} * x{l1}_{m1}" for m1 in range(2 * l1 + 1) if (m1, m2) in A]
                if terms:
                    new.append(f"          dY[{l2 * l2 + m2}] = fmaf(R, {' + '.join(terms)}, dY[{l2 * l2 + m2}]);")
            for m1, cgn in cg_names:
                new.append(f"          gx{l1}_{m1} = fmaf(R, {cgn}, gx{l1}_{m1});")
            ch_body.append("#if defined(__CUDA_ARCH__) && __CUDA_ARCH__ == 1200")
            ch_body += new
            ch_body.append("#else")
            ch_body += old
            ch_body.append("#endif")
            ch_body.append("        }")
