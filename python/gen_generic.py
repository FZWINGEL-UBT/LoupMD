def w3j(l1, l2, l3):
    return o3.wigner_3j(l1, l2, l3, dtype=torch.float64).numpy()


def _ptr_args(prefix, ls, const=True):
    q = "const float* __restrict__" if const else "float* __restrict__"
    return ", ".join(f"{q} {prefix}{l}" for l in ls)


def _lp_form(a, l, L):
    if a == 0 and L == l: return "scalar"
    if a == 1 and L == l + 1: return "raise"
    if a == 1 and L == l - 1: return "lower"
    raise ValueError((a, l, L))

def _lp_sym2(q):
    q0, q1, q2, q3, q4 = q.unbind(-1)
    return torch.stack([torch.stack([q0, q1, q2], -1), torch.stack([q1, q3, q4], -1),
                        torch.stack([q2, q4, -q0 - q3], -1)], -2)

def _lp_sym3n(q, n):
    q0, q1, q2, q3, q4, q5, q6 = q.unbind(-1)
    nx, ny, nz = n.unbind(-1)
    qxx = q0 * nx + q1 * ny + q2 * nz
    qxy = q1 * nx + q3 * ny + q4 * nz
    qxz = q2 * nx + q4 * ny + (-q0 - q3) * nz
    qyy = q3 * nx + q5 * ny + q6 * nz
    qyz = q4 * nx + q6 * ny + (-q1 - q5) * nz
    return torch.stack([torch.stack([qxx, qxy, qxz], -1), torch.stack([qxy, qyy, qyz], -1),
                        torch.stack([qxz, qyz, -qxx - qyy], -1)], -2)

def _lp_cartesian_f(a, l, L, x, n, q):
    if L == 0: h, gh = q[..., 0], torch.zeros_like(n)
    elif L == 1: h, gh = (q * n).sum(-1), q.expand_as(n)
    elif L == 2:
        v = torch.einsum("...ij,...j->...i", _lp_sym2(q), n)
        h, gh = (n * v).sum(-1), 2.0 * v
    else:
        v = torch.einsum("...ij,...j->...i", _lp_sym3n(q, n), n)
        h, gh = (n * v).sum(-1), 3.0 * v
    k = _lp_form(a, l, L)
    if k == "scalar": return x[..., 0] * h
    if k == "raise": return (x * gh).sum(-1)
    return (x * n).sum(-1) * h - (n * n).sum(-1) * (x * gh).sum(-1) / (2 * L + 1)

def lit(v):
    return float(np.float32(v)).hex() + "f"

def layout(lx):
    paths = eg.conv_paths(lx)
    count = [0, 0, 0, 0]
    slot = []
    for _, _, l3 in paths:
        slot.append((l3, count[l3]))
        count[l3] += 1
    return paths, slot, count

def fit_conversion(l1, l2, l3):
    W3 = o3.wigner_3j(l1, l2, l3, dtype=torch.float64)
    gen = torch.Generator().manual_seed(20261113)
    x = torch.randn(96, 2 * l1 + 1, generator=gen, dtype=torch.float64)
    n = torch.randn(96, 3, generator=gen, dtype=torch.float64)
    y = o3.spherical_harmonics(l2, n, normalize=False, normalization="component")
    target = torch.einsum("ijo,si,sj->so", W3, x, y)
    eye = torch.eye(2 * l3 + 1, dtype=torch.float64)
    phi = torch.stack([_lp_cartesian_f(l1, l2, l3, x, n, eye[c].expand(96, -1)) for c in range(2 * l3 + 1)], -1)
    M = torch.linalg.lstsq(phi, target).solution
    res = float((phi @ M - target).abs().max() / target.abs().max().clamp_min(1e-300))
    assert res < 1e-12, (l1, l2, l3, res)
    return M.numpy()

def emit_conv_fwd(lx, groups=(0, 1, 2), name=None):
    """Forward conv over layout(lx)'s paths whose x degree is in ``groups`` (table stride: all paths). A kernel
    launched with density_table = nullptr leaves D alone, so a split launch computes the density once."""
    paths, slot, count = layout(lx)
    n_paths = len(paths)
    name = name or f"gconv_fwd_L{lx}"
    sel = [(k, p) for k, p in enumerate(paths) if p[0] in groups]
    nacc = sum(2 * l3 + 1 for _, (_, _, l3) in sel)
    def _f32(x):
        return struct.unpack("f", struct.pack("f", x))[0]

    cg_terms = collections.OrderedDict()
    path_pairs = {}
    acc_off = 0
    for k, (l1, l2, l3) in sel:
        W = o3.wigner_3j(l1, l2, l3, dtype=torch.float64).numpy()
        p_keys = []
        for m3 in range(2 * l3 + 1):
            I = acc_off + m3
            for m1 in range(2 * l1 + 1):
                tlist = [(_f32(float(W[m1, m2, m3])), l2 * l2 + m2) for m2 in range(2 * l2 + 1) if abs(W[m1, m2, m3]) > 1e-12]
                if tlist:
                    assert (I, m1) not in cg_terms, (I, m1)
                    cg_terms[(I, m1)] = tlist
                    p_keys.append((I, m1))
        path_pairs[k] = p_keys
        acc_off += 2 * l3 + 1

    acc_scale, cg_use, extras = {}, {}, collections.OrderedDict()
    for I in range(nacc):
        singles = [abs(t[0][0]) for (i, _), t in cg_terms.items() if i == I and len(t) == 1]
        if singles:
            cnt = collections.Counter(round(s, 6) for s in singles)
            best = max(cnt.items(), key=lambda kv: kv[1])[0]
            sc = next(s for s in singles if round(s, 6) == best)
        else:
            sc = abs(next(t for (i, _), t in cg_terms.items() if i == I)[0][0])
        acc_scale[I] = sc
        for (i, m1), tlist in cg_terms.items():
            if i != I:
                continue
            norm = [(c / sc, ec) for c, ec in tlist]
            if len(norm) == 1 and abs(abs(norm[0][0]) - 1.0) < 1e-6:
                cg_use[(I, m1)] = ("-" if norm[0][0] < 0 else "", norm[0][1])
                continue
            sign = -1.0 if norm[0][0] < 0 else 1.0
            key = tuple(sorted((ec, lit(sign * c)) for c, ec in norm))
            if key not in extras:
                extras[key] = 16 + len(extras)
            cg_use[(I, m1)] = ("-" if sign < 0 else "", extras[key])

    ED = 4 * math.ceil((16 + len(extras)) / 4)
    def _extra_code(pad, idx_expr):
        if not extras:
            return ""
        ls = [f"{pad}{{ float* p = s_sh + ({idx_expr}) * ED;"]
        for key, eslot in extras.items():
            expr = " + ".join(f"{c_lit} * p[{ec}]" for ec, c_lit in key)
            ls.append(f"{pad}  p[{eslot}] = {expr};")
        ls.append(f"{pad}}}")
        return "\n" + "\n".join(ls)

    extra_hi = _extra_code("      ", "ch - 32")
    extra_lo = _extra_code("          ", "ch")

    body, body_pair = [], []
    for k, (l1, l2, l3) in sel:
        decode = [
            f"        const uint2 c = __ldg(tq + {k} * C + ch);",
            "        const unsigned eb0 = (c.y & 0x0F800000u) + bias_shift;",
            "        const float eb_f = __uint_as_float(eb0);",
            "        const float r0 = __uint_as_float((c.x & 0x7FFFF8u) | eb0);",
            "        const float r1 = __uint_as_float((c.y & 0x7FFFF0u) | eb0);",
            "        const float r2 = __uint_as_float((__funnelshift_l(c.x, c.x, 20) & 0x7FF800u) | eb0);",
            "        const float r3 = __uint_as_float((__funnelshift_l(c.y, c.y, 19) & 0x7F8000u) | eb0);",
            "        const float w = fmaf(pw.z, r3, fmaf(pw.y, r2, fmaf(pw.x, r1, fmaf(pw.w, eb_f, r0))));",
        ]
        m1_used = sorted({m1 for _, m1 in path_pairs[k]})
        body.append(f"      {{ // path {k} ({l1},{l2},{l3})")
        body += decode
        body_pair.append(f"      {{ // path {k} ({l1},{l2},{l3}) pair")
        body_pair += decode
        body_pair.append("        const float wB = fmaf(pwB.z, r3, fmaf(pwB.y, r2, fmaf(pwB.x, r1, fmaf(pwB.w, eb_f, r0))));")
        for m1 in m1_used:
            body.append(f"        const float xi_{m1} = __ldg(x{l1} + ((int64_t)snd * {2 * l1 + 1} + {m1}) * C + ch);")
            body_pair.append(f"        const float xi_{m1} = __ldg(x{l1} + ((int64_t)snd * {2 * l1 + 1} + {m1}) * C + ch);")
            body_pair.append(f"        const float xiB_{m1} = __ldg(x{l1} + ((int64_t)sndB * {2 * l1 + 1} + {m1}) * C + ch);")
        for I, m1 in path_pairs[k]:
            sg, eslot = cg_use[(I, m1)]
            body.append(f"        acc[{I}] = fmaf(w * xi_{m1}, {sg}she[{eslot}], acc[{I}]);")
            body_pair.append(f"        acc[{I}] = fmaf(w * xi_{m1}, {sg}she[{eslot}], acc[{I}]);")
            body_pair.append(f"        acc[{I}] = fmaf(wB * xiB_{m1}, {sg}sheB[{eslot}], acc[{I}]);")
        body.append("      }")
        body_pair.append("      }")

    stores = []
    acc_off = 0
    for k, (l1, l2, l3) in sel:
        _, j = slot[k]
        n = count[l3]
        for m3 in range(2 * l3 + 1):
            I = acc_off + m3
            sc = acc_scale[I]
            mult = "" if abs(sc - 1.0) < 1e-7 else f" * {lit(sc)}"
            stores.append(f"  mid{l3}[((int64_t)rcv * {2 * l3 + 1} + {m3}) * {n} * C + {j} * C + ch] = acc[{I}]{mult};")
        acc_off += 2 * l3 + 1

    x_args = ", ".join(f"const float* __restrict__ x{l}" for l in range(lx + 1))
    m_args = ", ".join(f"float* __restrict__ mid{l}" for l in range(4))
    # S99: zx{l} (nullable): the layer's x gradient rows of this receiver, zeroed here for the backward's atomics
    # instead of in the pass's zero slab (the forward conv is L2-bound, its spare DRAM bandwidth absorbs the stores).
    z_args = ", ".join(f"float* __restrict__ zx{l}" for l in range(lx + 1))
    zero_rows = "\n".join(
        f"    if (zx{l}) for (int i = ch; i < {2 * l + 1} * C; i += tpr) zx{l}[(int64_t)rcv * {2 * l + 1} * C + i] = 0.0f;"
        for l in range(lx + 1))
    return f"""template <int R, bool PAIR, int MAX_T = (R == 1 ? 256 : 128 * R), bool PRELOC = false, int C_FIX = 0>
__global__ void __launch_bounds__(MAX_T) {name}(
    int N, int C_arg, int S, int I, SplineGrid grid, int sh_perm, int pair_sym,
    const int* __restrict__ row_ptr, const int* __restrict__ senders, const float4* __restrict__ vec_len,
    const int* __restrict__ act_slab, const float2* __restrict__ act_t_sx,
    const int* __restrict__ species, const uint2* __restrict__ packed_table, const float4* __restrict__ density_table,
    unsigned bias_shift, {x_args}, {m_args}, float* __restrict__ D, {z_args}) {{
  const int C = C_FIX ? C_FIX : C_arg;
  constexpr int TILE = 32, ED = {ED};
  static_assert(R >= 1 && R <= 15, "bar.sync id limit");
  __shared__ int s_snd_all[R][TILE];
  __shared__ __align__(16) float4 s_pw_all[R][TILE];
  __shared__ int64_t s_tq_all[R][TILE];
  __shared__ __align__(16) float s_sh_all[R][TILE * ED];
  const int half = R == 1 ? 0 : (threadIdx.x >> 7), ch = R == 1 ? threadIdx.x : (threadIdx.x & 127);
  const int rcv = blockIdx.x * R + half;
  if (rcv >= N) return;
  {{  // S99: before the edge loop, so the zero targets are dead during it (no register pressure there)
    const int tpr = R == 1 ? (int)blockDim.x : 128;
{zero_rows}
  }}
  int* s_snd = s_snd_all[half];
  float4* s_pw = s_pw_all[half];
  int64_t* s_tq = s_tq_all[half];
  float* s_sh = s_sh_all[half];
  const int sa = species[rcv];
  float acc[{nacc}];
  #pragma unroll
  for (int i = 0; i < {nacc}; ++i) acc[i] = 0.0f;
  float dsum = 0.0f;
  const int eb = row_ptr[rcv], ee = row_ptr[rcv + 1];
  auto sync_grp = [&]() {{
    if (R == 1) __syncthreads();
    else asm volatile("bar.sync %0, 128;" :: "r"(half + 1) : "memory");
  }};
  for (int base = eb; base < ee; base += TILE) {{
    const int cnt = (ee - base < TILE) ? (ee - base) : TILE;
    if (ch >= 32 && ch - 32 < cnt) {{
      const float4 vl = __ldg(vec_len + base + (ch - 32));
      if (sh_perm) loup::edge_sh16(vl.y, vl.z, vl.x, vl.w, reinterpret_cast<float4*>(s_sh + (ch - 32) * ED));
      else         loup::edge_sh16(vl.x, vl.y, vl.z, vl.w, reinterpret_cast<float4*>(s_sh + (ch - 32) * ED));{extra_hi}
    }}
    if (ch < 32) {{
      float d_edge = 0.0f;
      if (ch < cnt) {{
        const int e = base + ch;
        const int snd = senders[e];
        int64_t slab;
        float t;
        if (PRELOC) {{
          slab = (int64_t)__ldg(act_slab + e);
          t = __ldg(act_t_sx + e).x;
        }} else {{
          const float4 vl = __ldg(vec_len + e);
          const int pr = pair_sym ? loup::sym_pair(species[snd], sa, S) : species[snd] * S + sa;
          int iv; float sxi;
          locate_spline(grid, vl.w, iv, t, sxi);
          slab = (int64_t)pr * I + iv;
        }}
        const float s = t - 0.5f, s_sq = s * s;
        const float s1 = s * 0x1.0p-8f, s2 = s_sq * 0x1.0p-14f, s3 = s * s_sq * 0x1.0p-19f;
        s_snd[ch] = snd;
        s_pw[ch] = make_float4(s1, s2, s3, -1.5f * (1.0f + s1 + s2 + s3));
        s_tq[ch] = slab * ({n_paths} * (int64_t)C);
        if (density_table) {{
          const float4 dc = __ldg(density_table + slab);
          d_edge = fmaf(t, fmaf(t, fmaf(t, dc.w, dc.z), dc.y), dc.x);
        }}
        if (C < 64) {{
          const float4 vl = __ldg(vec_len + e);
          if (sh_perm) loup::edge_sh16(vl.y, vl.z, vl.x, vl.w, reinterpret_cast<float4*>(s_sh + ch * ED));
          else         loup::edge_sh16(vl.x, vl.y, vl.z, vl.w, reinterpret_cast<float4*>(s_sh + ch * ED));{extra_lo}
        }}
      }}
      if (density_table) {{
        #pragma unroll
        for (int off = 16; off > 0; off >>= 1) d_edge += __shfl_xor_sync(0xffffffffu, d_edge, off);
        if (ch == 0) dsum += d_edge;
      }}
    }}
    sync_grp();
    for (int k = 0; k < cnt;) {{
      const int snd = s_snd[k];
      const float4 pw = s_pw[k];
      const float* she = s_sh + k * ED;
      const uint2* tq = packed_table + s_tq[k];
      if (PAIR && k + 1 < cnt && s_tq[k + 1] == s_tq[k]) {{
        const int sndB = s_snd[k + 1];
        const float4 pwB = s_pw[k + 1];
        const float* sheB = she + ED;
{chr(10).join(body_pair)}
        k += 2;
      }} else {{
{chr(10).join(body)}
        k += 1;
      }}
    }}
    sync_grp();
  }}
  if (density_table && ch == 0) D[rcv] = dsum;
{chr(10).join(stores)}
}}
"""

# Per-edge force-vector update at the end of the backward convs (one lane per edge, so each element has one writer in
# the kernel). EDGE_DVEC_RED: on sm_120 a fire-and-forget atomic add, which rounds like the read-add-store (except
# that it flushes subnormals, ~1e-38, which these per-edge forces never reach) without a load to wait on: the
# read-modify-write's load was ~4% of gconv_bwd_L0's stall samples and the atomics made it 8-16% faster (S40). Used
# only for lx 0, where that was measured; lx 1 / 2 (1-2%) and other GPUs keep the read-add-store.
EDGE_DVEC_RMW = """\
      edge_dvec[(int64_t)e * 3 + 0] += fx;
      edge_dvec[(int64_t)e * 3 + 1] += fy;
      edge_dvec[(int64_t)e * 3 + 2] += fz;"""
EDGE_DVEC_RED = """\
#if defined(__CUDA_ARCH__) && __CUDA_ARCH__ == 1200
      atomicAdd(edge_dvec + (int64_t)e * 3 + 0, fx);
      atomicAdd(edge_dvec + (int64_t)e * 3 + 1, fy);
      atomicAdd(edge_dvec + (int64_t)e * 3 + 2, fz);
#else
""" + EDGE_DVEC_RMW + """
#endif"""
# S98: the backward of the top conv layer runs first in the pass and assigns the per-edge vectors instead (no zero
# fill of the buffer, no load to wait on); dvec_assign is uniform per launch.
EDGE_DVEC_SET = """\
      edge_dvec[(int64_t)e * 3 + 0] = fx;
      edge_dvec[(int64_t)e * 3 + 1] = fy;
      edge_dvec[(int64_t)e * 3 + 2] = fz;"""

def emit_conv_bwd_lp(lx):
    """Late pull-back backward over layout(lx)'s paths with x degree <= 1: every path for lx 0 / 1; for lx 2 the ten
    paths of lx 1 indexed into the 17-path table (gconv_bwd_L2lp, which also owns the density term); the x degree 2
    paths then run in gconv_bwd_L2."""
    paths, slot, count = layout(lx)
    n_paths = len(paths)
    xl = min(lx, 1)
    name = f"gconv_bwd_L{lx}" if lx <= 1 else "gconv_bwd_L2lp"
    slots = []
    n_slots = 0
    for k, (l1, l2, l3) in enumerate(paths):
        if l1 > 1:
            continue
        form = _lp_form(l1, l2, l3)
        sz = 2 * l3 + 1
        slots.append((k, l1, l2, l3, form, n_slots, sz))
        n_slots += sz
    QS = ((n_slots + 3) // 4) * 4
    if (QS // 4) % 2 == 0:
        QS += 4

    pro = ["  for (int ch = tid; ch < C; ch += blockDim.x) {"]
    for k, l1, l2, l3, form, q0, sz in slots:
        M = fit_conversion(l1, l2, l3)
        _, j = slot[k]
        n = count[l3]
        for o in range(2 * l3 + 1):
            pro.append(f"    const float g_{k}_{o} = __ldg(dmid{l3} + ((int64_t)rcv * {2 * l3 + 1} + {o}) * {n} * C + {j} * C + ch);")
        for s_idx in range(sz):
            terms = [f"{lit(M[s_idx, o])} * g_{k}_{o}" for o in range(2 * l3 + 1) if abs(M[s_idx, o]) > 1e-12]
            pro.append(f"    s_q[ch * {QS} + {q0 + s_idx}] = {' + '.join(terms) if terms else '0.0f'};")
    pro.append("  }")
    pro.append("  __syncthreads();")

    ch_body = []
    ch_body.append(f"      const float4* sq4 = reinterpret_cast<const float4*>(s_q + ch * {QS});")
    for idx in range(QS // 4):
        ch_body.append(f"      const float4 Q{idx} = sq4[{idx}];")
    def q_ref(s_idx):
        return f"Q{s_idx // 4}.{['x', 'y', 'z', 'w'][s_idx % 4]}"

    ch_body.append("      const float x0 = __ldg(x0_p + (int64_t)snd * C + ch);")
    ch_body.append("      float dx0_acc = 0.0f;")
    if xl >= 1:
        ch_body.append("      const float xx = __ldg(x1_p + ((int64_t)snd * 3 + 0) * C + ch);")
        ch_body.append("      const float xy = __ldg(x1_p + ((int64_t)snd * 3 + 1) * C + ch);")
        ch_body.append("      const float xz = __ldg(x1_p + ((int64_t)snd * 3 + 2) * C + ch);")
        ch_body.append("      float dx1_0 = 0.0f, dx1_1 = 0.0f, dx1_2 = 0.0f;")

